/**
 * Figma naming parity table (REL-005).
 *
 * Reads `docs/manifest.json` and writes `docs/figma/component-parity.md`: one row per component
 * with the Figma component path and its variant properties, derived from the `variant`, `size`
 * and `tone` unions and the boolean state props. No Figma API calls; the table is the contract
 * the Figma library must follow so Code Connect and humans can match components by name.
 *
 *   pnpm figma:parity           write docs/figma/component-parity.md
 *   pnpm figma:parity --check   fail when the committed file is stale
 *
 * Run it after `pnpm manifest:build`.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

interface ManifestComponent {
  name: string;
  status: string;
  stories?: { title?: string };
  props: { name: string; type: string; deprecated?: string }[];
  variants: { variant?: string[]; size?: string[]; tone?: string[] };
}

export const OUTPUT = 'docs/figma/component-parity.md';

/** Boolean props that are state, not content: they become Figma boolean properties. */
const STATE_PROPS = /^(is[A-Z]\w*|fullWidth|dense|compact|inline|loading|disabled|invalid)$/;
/** Props that are plumbing in React Aria and have no visual meaning in a design file. */
const SKIP_PROPS = new Set(['isDisabled']);

/** `isReadOnly` becomes `Read only`; `fullWidth` becomes `Full width`. */
export function figmaPropertyName(prop: string): string {
  const bare = /^is[A-Z]/.test(prop) ? prop.slice(2) : prop;
  const words = bare.replace(/([a-z0-9])([A-Z])/g, '$1 $2').toLowerCase();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

/** `danger-solid` becomes `Danger solid`: variant values are sentence case in Figma. */
export function figmaValue(value: string): string {
  const words = value.replaceAll('-', ' ');
  return words.charAt(0).toUpperCase() + words.slice(1);
}

export function figmaPath(component: ManifestComponent): string {
  const group = component.stories?.title?.split('/')[0] ?? 'Components';
  return `${group}/${component.name}`;
}

export function variantProperties(component: ManifestComponent): string[] {
  const rows: string[] = [];
  for (const key of ['variant', 'size', 'tone'] as const) {
    const values = component.variants[key];
    if (values?.length) {
      // Sizes stay as written (sm / md / lg): they are abbreviations, not words.
      const shown = key === 'size' ? values : values.map(figmaValue);
      rows.push(`${figmaPropertyName(key)} = ${shown.join(' / ')}`);
    }
  }
  return rows;
}

export function booleanProperties(component: ManifestComponent): string[] {
  return component.props
    .filter((p) => p.type === 'boolean' && STATE_PROPS.test(p.name) && !SKIP_PROPS.has(p.name))
    .filter((p) => p.deprecated === undefined)
    .map((p) => figmaPropertyName(p.name));
}

const cell = (items: string[]): string => (items.length ? items.join('<br>') : 'none');

export function buildParityMarkdown(components: ManifestComponent[]): string {
  const sorted = [...components].sort((a, b) => a.name.localeCompare(b.name));
  const withVariants = sorted.filter(
    (c) => variantProperties(c).length > 0 || booleanProperties(c).length > 0,
  ).length;
  const lines = [
    '# Figma component parity',
    '',
    'Generated by `pnpm figma:parity` from `docs/manifest.json`. Do not edit by hand.',
    '',
    `${String(sorted.length)} components, ${String(withVariants)} with variant or state properties. Naming rules are in [Figma workflow](./README.md#component-naming-parity).`,
    '',
    '| Code component | Figma component | Variant properties | Boolean properties | Status |',
    '| --- | --- | --- | --- | --- |',
    ...sorted.map(
      (c) =>
        `| \`${c.name}\` | \`${figmaPath(c)}\` | ${cell(variantProperties(c))} | ${cell(booleanProperties(c))} | ${c.status} |`,
    ),
    '',
  ];
  return lines.join('\n');
}

function main(): void {
  const root = fileURLToPath(new URL('../../', import.meta.url));
  const manifest = JSON.parse(readFileSync(path.join(root, 'docs/manifest.json'), 'utf8')) as {
    components: ManifestComponent[];
  };
  const next = buildParityMarkdown(manifest.components);
  const target = path.join(root, OUTPUT);
  if (process.argv.includes('--check')) {
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null;
    if (current !== next) {
      console.error(`${OUTPUT} is stale. Run \`pnpm figma:parity\` and commit the result.`);
      process.exit(1);
    }
    console.log('Figma parity table is up to date.');
    return;
  }
  mkdirSync(path.dirname(target), { recursive: true });
  writeFileSync(target, next);
  console.log(`Wrote ${OUTPUT}.`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
