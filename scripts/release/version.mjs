// REL-002: `pnpm changeset:version`
//
// Changesets always writes CHANGELOG.md next to package.json, and this repository already has a
// hand-maintained root CHANGELOG.md (the TODO task log, see AGENTS.md rule 2). To avoid clobbering
// it, this script:
//   1. moves the task log aside,
//   2. runs `changeset version` (bumps package.json, consumes .changeset/*.md, writes CHANGELOG.md),
//   3. moves the generated section into docs/release/CHANGELOG.md (consumer-facing release notes),
//   4. restores the task log and turns its [Unreleased] heading into the released version.
// Pass --cwd <dir> to run against another checkout (used by tests).
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, renameSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const cwdIndex = args.indexOf('--cwd');
const root =
  cwdIndex >= 0
    ? resolve(args[cwdIndex + 1])
    : resolve(dirname(fileURLToPath(import.meta.url)), '../..');

const taskLog = join(root, 'CHANGELOG.md');
const aside = join(root, 'CHANGELOG.tasks.md.tmp');
const releaseNotes = join(root, 'docs/release/CHANGELOG.md');
const HEADER =
  '# Release notes\n\nGenerated by Changesets (`pnpm changeset:version`). Newest first. The task-level log is the root `CHANGELOG.md`.\n';

const before = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
if (existsSync(taskLog)) renameSync(taskLog, aside);

let status = 1;
try {
  const bin = args.includes('--changeset-bin')
    ? args[args.indexOf('--changeset-bin') + 1]
    : 'pnpm exec changeset';
  status = spawnSync(`${bin} version`, { cwd: root, stdio: 'inherit', shell: true }).status ?? 1;
} finally {
  const generated = existsSync(taskLog) ? readFileSync(taskLog, 'utf8') : '';
  if (existsSync(aside)) renameSync(aside, taskLog);
  if (status === 0 && generated) {
    // Drop the "# loui-ds" title Changesets adds; keep the "## x.y.z" sections.
    const sections = generated.replace(/^# .*\n+/, '').trim();
    const previous = existsSync(releaseNotes)
      ? readFileSync(releaseNotes, 'utf8').replace(/^# Release notes[\s\S]*?\n(?=## )/, '')
      : '';
    mkdirSync(dirname(releaseNotes), { recursive: true });
    writeFileSync(releaseNotes, `${HEADER}\n${sections}\n\n${previous}`.trimEnd() + '\n');
  }
}
if (status !== 0) process.exit(status);

const after = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;
if (after !== before && existsSync(taskLog)) {
  // Local calendar date (D-B1): `toISOString()` is UTC and dated an evening release a day late.
  const date = new Date().toLocaleDateString('en-CA');
  const log = readFileSync(taskLog, 'utf8').replace(
    /^## \[Unreleased\]\s*$/m,
    `## [Unreleased]\n\n## [${after}] - ${date}`,
  );
  writeFileSync(taskLog, log);
  console.log(`Root CHANGELOG.md: [Unreleased] entries now belong to [${after}].`);
}
console.log(`Release notes written to docs/release/CHANGELOG.md (version ${before} -> ${after}).`);
